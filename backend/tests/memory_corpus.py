def meeting_start(i: int) -> datetime:
    return START + timedelta(days=7 * i)


def gold_pairs(assign: dict[tuple[int, str], str]) -> dict[str, float]:
    """Сравнение с эталоном по парам вхождений: пара «в одной сквозной теме» в эталоне и в результате. assign — {(встреча, тема): поток}."""
    occ = [(i, t["id"], t["gold"]) for i, m in enumerate(MEETINGS) for t in m]
    tp = fp = fn = 0
    for a in range(len(occ)):
        for b in range(a + 1, len(occ)):
            g = occ[a][2] == occ[b][2]
            p = assign.get(occ[a][:2]) is not None and assign.get(occ[a][:2]) == assign.get(occ[b][:2])
            tp += g and p
            fp += (not g) and p
            fn += g and not p
    return {"precision": round(tp / (tp + fp), 3) if tp + fp else 1.0, "recall": round(tp / (tp + fn), 3) if tp + fn else 1.0, "false_merges": fp, "missed_links": fn}
