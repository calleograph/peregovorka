def _with_filler(t: "Topic", rng_seed: int) -> list[tuple[str, str]]:
    import random
    rnd = random.Random(rng_seed)
    a, b = NOUNS[t.key]
    extra = [(w, x.format(a=a, b=b)) for w, x in FILLER]
    rnd.shuffle(extra)
    out = list(t.lines)
    for i, ln in enumerate(extra[:8]):
        out.insert(min(len(out) - 1, 3 + i * 2), ln)          # вставки в середину темы: вступление и итог остаются на местах
    return out


@dataclass
class Corpus:
    name: str
    text: str                                      # стенограмма в формате протокола: шапка + «[ЧЧ:ММ:СС] Имя: текст»
    rows: list[dict]                               # реплики: sec (от начала), clock, speaker, text, topic
    topics: list[Topic]
    topic_span: dict[str, tuple[int, int]]         # key → (начало, конец), секунды от начала встречи
    duration_s: int
    started: datetime

    @property
    def chars(self) -> int:
        return len(self.text)


def build(name: str, *, started: datetime | None = None, pace: float = 1.0) -> Corpus:
    """Собирает стенограмму выбранного размера. Время реплики растёт пропорционально её длине (≈ 14 знаков в секунду речи) плюс небольшая пауза."""
    started = started or datetime(2026, 10, 27, 10, 0, 0)
    topics = [ALL[k] for k in SIZES[name]]
    seq: list[tuple[str, str, str | None]] = [(s, t, None) for s, t in CHATTER]
    for n, t in enumerate(topics):
        for s, x in (_with_filler(t, n) if name == "xlong" else t.lines):
            seq.append((s, x, t.key))
    # возвращение к ранее обсуждавшейся теме — ближе к концу длинной и средней встречи
    if name in ("medium", "long", "xlong"):
        for k in ("db",) + (("2fa", "rel") if name != "medium" else ()):
            s, x = RETURN_LINES[k]
            seq.append((s, x, k))
    seq += [(s, t, None) for s, t in CLOSING]
    rows: list[dict] = []
    sec = 0.0
    for who, text, key in seq:
        rows.append({"sec": int(sec), "speaker": PEOPLE[who], "text": text, "topic": key})
        sec += max(6.0, len(text) / 14.0 * pace) + 2.5
    duration = int(sec)
    span: dict[str, tuple[int, int]] = {}
    for r in rows:
        k = r["topic"]
        if k and k not in span:
            span[k] = (r["sec"], r["sec"])
    # у темы несколько отрезков (возврат) — границы берём по первому вхождению до конца её основного блока
    for t in topics:
        own = [r["sec"] for r in rows if r["topic"] == t.key]
        main = [r["sec"] for r in rows[: len(rows)] if r["topic"] == t.key]
        span[t.key] = (min(own), max(main))
    for r in rows:
        r["clock"] = (started + timedelta(seconds=r["sec"])).strftime("%H:%M:%S")
    end = started + timedelta(seconds=duration)
    head = [
        "Переговорка: Совещание ИТ-отдела",
        f"Дата: {started:%Y-%m-%d} (вторник)",
        f"Начало: {started:%H:%M} — окончание: {end:%H:%M}",
        "Участвовали: " + ", ".join(PEOPLE[k] for k in "SADEP"),
        "",
    ]
    text = "\n".join(head + [f"[{r['clock']}] {r['speaker']}: {r['text']}" for r in rows]) + "\n"
    return Corpus(name, text, rows, topics, span, duration, started)


