/**
 * Текст об остановленной транскрибации по ФАКТИЧЕСКОМУ состоянию записей (события recording_changed от сервера), а не по настройке комнаты:
 * транскрибация — текст, аудиозапись — звук встречи, видеозапись — видео (в продукте пока не выпускается: video всегда false, см. docs/RECORDINGS.md).
 */
export function transcriptionStoppedText(audio: boolean, video: boolean): string {
  if (audio && video) return "Транскрибация остановлена. Аудио- и видеозапись продолжаются";
  if (video) return "Транскрибация остановлена. Видеозапись продолжается";
  if (audio) return "Транскрибация остановлена. Аудиозапись продолжается";
  return "Транскрибация остановлена";
}
