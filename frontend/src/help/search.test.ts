import { describe, expect, it } from "vitest";
import index from "./helpIndex.json";
import { searchHelp, type HelpItem } from "./search";

const top = (q: string) => searchHelp(index.items as HelpItem[], q, 3).map((i) => i.page);

describe("справка находит инструкцию по вопросу обычными словами", () => {
  it.each([
    ["Как включить демонстрацию экрана?", "Как-показать-экран"],
    ["Почему меня не слышат?", "Решение-проблем-микрофона"],
    ["Где скачать запись?", "Где-найти-материалы-встречи"],
    ["Как отправить протокол?", "Как-отправить-материалы"],
    ["Как подключить гостя?", "Как-подключить-гостя"],
    ["Как перенести файлы на другой диск?", "Как-перенести-данные-между-хранилищами"],
    ["Почему трансляция не запускается?", "Решение-проблем-видеозаписи-и-трансляций"],
    ["Как подключить почтовый сервер?", "Как-подключить-почту"],
    ["бэкап", "Как-сделать-резервную-копию-и-перенести-сервер"],
    ["шаринг", "Как-показать-экран"],
  ])("%s", (q, page) => { expect(top(q)).toContain(page); });

  it("пустой запрос и запрос из служебных слов ничего не находят", () => {
    expect(searchHelp(index.items as HelpItem[], "   ")).toEqual([]);
    expect(searchHelp(index.items as HelpItem[], "как где почему")).toEqual([]);
  });

  it("каждая статья показана один раз", () => {
    const pages = searchHelp(index.items as HelpItem[], "как показать экран", 12).map((i) => i.page);
    expect(new Set(pages).size).toBe(pages.length);
  });
});
