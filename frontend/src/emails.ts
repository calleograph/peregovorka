/** Один вид адреса для всех форм: то же правило, что на сервере (EMAIL_RE в backend/app/services/mail.py), включая внутренние адреса вида name@host.
 * Иначе один адрес проходил бы в одной форме и отклонялся в другой. */
export const EMAIL = /^[A-Za-z0-9.!#$%&'*+/=?^_`{|}~-]{1,64}@[A-Za-z0-9]([A-Za-z0-9.-]{0,251}[A-Za-z0-9])?\.[A-Za-z]{2,63}$|^[A-Za-z0-9.!#$%&'*+/=?^_`{|}~-]{1,64}@[A-Za-z0-9-]{1,63}$/;
export const isEmail = (s: string) => EMAIL.test(s.trim());
